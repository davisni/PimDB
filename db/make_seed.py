"""Builds db/seed.sql for the prototype from the latch's Ecom Records.

Reads data/ecom_897788M91.json (not in Git) and writes db/seed.sql.
Run from the repository root:  python3 db/make_seed.py

Everything marked "demo" is invented for the prototype: approvals, confidence
scores, the five managed offers and their prices and channel IDs.
"""
import json
import re
from collections import OrderedDict

ITEM = {"netsuite_id": 19954, "sku": "897788M91", "description": "Latch Assembly"}
ITEM_REFERENCE_NUMBERS = ("182367M1, 184779M92, 184779M92-A, 194119M91, 194119M91-A, "
                          "897788M91, 962148M91, M12-07-01, MFS148, s41228, s41228-A")

# (netsuite_id, name, brand_name)
ACCOUNTS = [
    (1, "Reliable Aftermarket Parts", "Reliable Aftermarket Parts"),
    (2, "Stevens Lake", "Stevens Lake Parts"),
    (3, "Tractor Parts Accessories", "Tractor Parts Accessories"),
    (4, "Reliable (Canada)", "Reliable Aftermarket Parts"),
    (5, "AIC", "AIC Replacement Parts"),
    (6, "Aftermarket Concrete", "Aftermarket Concrete"),
    (7, "Aftermarket Powersports", "Aftermarket Powersports"),
]
CHANNELS = [("amazon", "Amazon"), ("ebay", "eBay"), ("walmart", "Walmart"), ("shopify", "Shopify store")]

# (code, label, data_type, is_multi, uses_make, risk)
ATTRIBUTES = [
    ("part_type", "Part type", "text", False, False, "low"),
    ("equipment_type", "Equipment type", "text", True, False, "low"),
    ("replaces_part_number", "Replaces part number", "text", True, False, "high"),
    ("fits_model", "Fits model", "text", True, True, "high"),
    ("interchangeable_with", "Interchangeable with", "text", True, False, "high"),
]

STANDARD_BULLETS = [
    "OEM Numbers Are Provided for Reference Only. Please Verify Fit Prior To Ordering.",
    "Please Note: Some Listings Use Stock Images for Reference and May Differ from the Actual Product.",
    "All OEM part numbers and logos are to be used for identification purposes only.",
]

# Assumed until confirmed against each channel's own schema.
# (channel, field, required, max_length, max_items, built_from)
CHANNEL_RULES = [
    ("amazon", "item_name", True, 200, None, "template:title"),
    ("amazon", "brand", True, None, None, "listing.brand_on_listing"),
    ("amazon", "part_number", True, None, None, "branded_product.part_number"),
    ("amazon", "bullet_point", False, 500, 5, "template:bullets"),
    ("amazon", "product_description", False, 2000, None, "template:description"),
    ("ebay", "title", True, 80, None, "template:title"),
    ("ebay", "brand", True, None, None, "listing.brand_on_listing"),
    ("ebay", "mpn", True, None, None, "branded_product.part_number"),
    ("ebay", "description", True, None, None, "template:description"),
    ("walmart", "productName", True, 200, None, "template:title"),
    ("walmart", "brand", True, None, None, "listing.brand_on_listing"),
    ("walmart", "keyFeatures", False, None, 5, "template:bullets"),
]

# The clean, managed side of the demo. Prices and channel IDs are invented.
# (account, channel, variant, seller_sku, price, listing_type, channel_id, brand, status, message)
DEMO_OFFERS = [
    ("Reliable Aftermarket Parts", "amazon", "Massey Ferguson", "RAP-897788M91-MF", 24.99,
     "owned", "B0EXAMPLE01", None, "live", None),
    ("Reliable Aftermarket Parts", "amazon", "Massey Harris", "RAP-897788M91-MH", 24.99,
     "owned", "B0EXAMPLE02", None, "live", None),
    ("Reliable Aftermarket Parts", "ebay", "", "RAP-897788M91", 22.99,
     "owned", "326000000001", None, "live", None),
    ("Stevens Lake", "amazon", "Massey Ferguson", "SLP-897788M91-MF", 21.99,
     "owned", None, None, "waiting_for_content", "Fitment for Massey Ferguson is not fully approved."),
    ("Reliable Aftermarket Parts", "amazon", "", "RAP-J-897788M91", 26.99,
     "joined", "B0EXAMPLE09", "Generic", "blocked",
     "Pack quantity mismatch: the page sells a set of 2, this item is 1."),
]


def q(value):
    """SQL literal."""
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def split_list(text):
    return [part.strip() for part in text.split(",") if part.strip()]


def make_from_title(title):
    if not title:
        return "Not stated"
    harris, ferguson = "Massey Harris" in title, "Massey Ferguson" in title
    if harris and not ferguson:
        return "Massey Harris"
    if ferguson and not harris:
        return "Massey Ferguson"
    if harris and ferguson:
        return "Massey Ferguson and Massey Harris"
    return "Not stated"


def main():
    records = json.load(open("data/ecom_897788M91.json"))
    out = []
    emit = out.append

    emit("-- Generated by db/make_seed.py. Do not edit by hand; edit the script and rerun it.")
    emit("-- Demo data for item 897788M91. Approvals, confidence, managed offers, prices and")
    emit("-- B0EXAMPLE channel IDs are invented for the prototype.")
    emit("BEGIN;")
    emit("TRUNCATE issue_fact, issue, listing_snapshot_fact, listing_snapshot, listing_override,")
    emit("  channel_rule, offer, listing, image, branded_product, fact_source, fact, source,")
    emit("  raw_import, item, attribute, channel, brand_content, seller_account RESTART IDENTITY CASCADE;")
    emit("")

    account_id = {}
    for i, (ns_id, name, brand) in enumerate(ACCOUNTS, start=1):
        account_id[name] = i
        emit(f"INSERT INTO seller_account (id, netsuite_id, name, brand_name) OVERRIDING SYSTEM VALUE "
             f"VALUES ({i}, {ns_id}, {q(name)}, {q(brand)});")
    brand_of = {name: brand for _, name, brand in ACCOUNTS}
    for name in ("Reliable Aftermarket Parts", "Stevens Lake"):
        for n, bullet in enumerate(STANDARD_BULLETS, start=1):
            emit(f"INSERT INTO brand_content VALUES ({account_id[name]}, 'standard_bullet_{n}', {q(bullet)});")
    for code, name in CHANNELS:
        emit(f"INSERT INTO channel VALUES ({q(code)}, {q(name)});")
    attribute_id = {}
    for i, (code, label, data_type, multi, uses_make, risk) in enumerate(ATTRIBUTES, start=1):
        attribute_id[code] = i
        emit(f"INSERT INTO attribute (id, code, label, data_type, is_multi, uses_make, risk) OVERRIDING SYSTEM VALUE "
             f"VALUES ({i}, {q(code)}, {q(label)}, {q(data_type)}, {q(multi)}, {q(uses_make)}, {q(risk)});")
    emit("")
    emit(f"INSERT INTO item (id, netsuite_id, sku, description) OVERRIDING SYSTEM VALUE "
         f"VALUES (1, {ITEM['netsuite_id']}, {q(ITEM['sku'])}, {q(ITEM['description'])});")
    emit("")

    # --- the "before": raw records and one source per record -----------------
    raw_id = 0
    source_id = 0
    source_of_record = {}

    def add_raw(system, record_type, external_id, payload):
        nonlocal raw_id
        raw_id += 1
        emit(f"INSERT INTO raw_import (id, source_system, record_type, external_id, item_id, payload) "
             f"OVERRIDING SYSTEM VALUE VALUES ({raw_id}, {q(system)}, {q(record_type)}, {q(external_id)}, 1, "
             f"{q(json.dumps(payload))}::jsonb);")
        return raw_id

    def add_source(kind, label, excerpt=None, raw=None):
        nonlocal source_id
        source_id += 1
        emit(f"INSERT INTO source (id, kind, label, excerpt, raw_import_id) OVERRIDING SYSTEM VALUE "
             f"VALUES ({source_id}, {q(kind)}, {q(label)}, {q(excerpt)}, {q(raw)});")
        return source_id

    item_raw = add_raw("netsuite", "item", str(ITEM["netsuite_id"]),
                       {"itemid": ITEM["sku"], "reference_numbers": ITEM_REFERENCE_NUMBERS,
                        "makes": "Massey Ferguson, Massey Harris"})
    item_source = add_source("legacy", "NetSuite item record 897788M91", ITEM_REFERENCE_NUMBERS, item_raw)
    vendor_note_source = add_source(
        "staff", "Note typed into a vendor part-number field on the item",
        "DO NOT USE. THEY ARE DIFFERENT")

    for rec in records:
        raw = add_raw("netsuite", "ecom_record", str(rec["id"]), rec)
        state = "inactive" if rec["isinactive"] == "T" else "active"
        label = f"Ecom Record {rec['id']} ({rec['account']}, SKU {rec['custrecord_sku'] or 'none'}, {state})"
        excerpt = " | ".join(x for x in (rec["custrecord_title_long"], rec["custrecord_models"],
                                          rec["custrecord_mpn"]) if x)
        source_of_record[rec["id"]] = add_source("legacy", label, excerpt or None, raw)
    emit("")

    # --- facts ---------------------------------------------------------------
    # key: (attribute, make, value_lower) -> {"value": original, "sources": set}
    claims = OrderedDict()

    def claim(attribute, make, value, src):
        key = (attribute, make, value.lower())
        claims.setdefault(key, {"value": value, "sources": []})
        if src not in claims[key]["sources"]:
            claims[key]["sources"].append(src)

    for number in split_list(ITEM_REFERENCE_NUMBERS):
        claim("replaces_part_number", None, number, item_source)
    for rec in records:
        src = source_of_record[rec["id"]]
        if rec["custrecord_mpn"] and rec["custrecord_mpn"] != "Does Not Apply":
            for number in split_list(rec["custrecord_mpn"]):
                claim("replaces_part_number", None, number, src)
        if rec["custrecord_models"]:
            make = make_from_title(rec["custrecord_title_long"])
            for model in split_list(rec["custrecord_models"]):
                claim("fits_model", make, model, src)
        if rec["custrecord_equipment"]:
            claim("equipment_type", None, rec["custrecord_equipment"], src)
        if rec["custrecord_typepart"]:
            claim("part_type", None, rec["custrecord_typepart"], src)

    fact_id = 0
    counts = {"approved": 0, "proposed": 0, "rejected": 0}

    def add_fact(attribute, make, value, sources, status, confidence, note, negative=False, proposed_by="legacy load"):
        nonlocal fact_id
        fact_id += 1
        decided = status in ("approved", "rejected")
        emit(f"INSERT INTO fact (id, item_id, attribute_id, make, value, is_negative, confidence, status, "
             f"proposed_by, decided_by, decided_at, decision_note) OVERRIDING SYSTEM VALUE VALUES ("
             f"{fact_id}, 1, {attribute_id[attribute]}, {q(make)}, {q(value)}, {q(negative)}, {confidence}, "
             f"{q(status)}, {q(proposed_by)}, {q('demo reviewer') if decided else 'NULL'}, "
             f"{'now()' if decided else 'NULL'}, {q(note)});")
        for s in sources:
            emit(f"INSERT INTO fact_source VALUES ({fact_id}, {s});")
        counts[status] += 1

    junk = re.compile(r"^(several|other|super)$|&", re.I)
    for (attribute, make, _), info in claims.items():
        support = len(info["sources"])
        confidence = min(0.95, round(0.35 + 0.15 * support, 2))
        if junk.search(info["value"]):
            status, note = "rejected", "Demo: not a usable value."
        elif attribute in ("replaces_part_number", "fits_model") and support >= 3 and make != "Not stated":
            status, note = "approved", "Demo approval. Agreement between records, not verified against a manufacturer source."
        else:
            status, note = "proposed", None
        add_fact(attribute, make, info["value"], info["sources"], status, confidence, note)

    add_fact("part_type", None, "Hood latch assembly", [item_source], "approved", 0.9,
             "Demo approval.", proposed_by="demo reviewer")
    add_fact("interchangeable_with", None, "One vendor's equivalent part (see source note)",
             [vendor_note_source], "proposed", 0.6, None, negative=True, proposed_by="legacy load")
    emit("")

    # --- the "before" on the listing side: existing listings, adopted as legacy
    listing_id = 0
    seen = set()
    for rec in records:
        if rec["isinactive"] == "T":
            continue
        for channel, sell, ident in (("amazon", "custrecord_a_sell", "custrecord_a_id"),
                                     ("ebay", "custrecord_e_sell", "custrecord_e_id"),
                                     ("walmart", "custrecord_w_sell", "custrecord_w_id")):
            if rec[sell] == "T" and rec[ident] and (channel, rec[ident]) not in seen:
                seen.add((channel, rec[ident]))
                listing_id += 1
                emit(f"INSERT INTO listing (id, channel_code, item_id, listing_type, control, channel_listing_id, "
                     f"brand_on_listing, status, status_message) OVERRIDING SYSTEM VALUE VALUES ({listing_id}, "
                     f"{q(channel)}, 1, 'owned', 'legacy', {q(rec[ident])}, {q(brand_of[rec['account']])}, 'live', "
                     f"{q('Adopted from Ecom Record %s. The PIM sends nothing to it.' % rec['id'])});")
    legacy_listings = listing_id
    emit("")

    # --- the "after": managed branded products, listings and offers ----------
    product_id = {}
    for n, (account, channel, variant, sku, price, ltype, channel_id, brand, status, message) in enumerate(DEMO_OFFERS, start=1):
        bp = None
        if ltype == "owned":
            key = (account, variant)
            if key not in product_id:
                product_id[key] = len(product_id) + 1
                emit(f"INSERT INTO branded_product (id, item_id, seller_account_id, variant, part_number) "
                     f"OVERRIDING SYSTEM VALUE VALUES ({product_id[key]}, 1, {account_id[account]}, {q(variant)}, {q(sku)});")
            bp = product_id[key]
        listing_id += 1
        emit(f"INSERT INTO listing (id, channel_code, item_id, branded_product_id, listing_type, control, "
             f"channel_listing_id, brand_on_listing, status, status_message) OVERRIDING SYSTEM VALUE VALUES ("
             f"{listing_id}, {q(channel)}, 1, {q(bp)}, {q(ltype)}, 'managed', {q(channel_id)}, "
             f"{q(brand or brand_of[account])}, {q(status)}, {q(message)});")
        emit(f"INSERT INTO offer (id, item_id, seller_account_id, channel_code, variant, seller_sku, price, "
             f"fulfilment, shipping_template, is_active, listing_id) OVERRIDING SYSTEM VALUE VALUES ("
             f"{n}, 1, {account_id[account]}, {q(channel)}, {q(variant)}, {q(sku)}, {price}, 'merchant', "
             f"{q('Demo standard')}, {q(status == 'live')}, {listing_id});")
    emit("")

    for channel, field, required, max_length, max_items, built_from in CHANNEL_RULES:
        emit(f"INSERT INTO channel_rule (channel_code, field_code, is_required, max_length, max_items, built_from) "
             f"VALUES ({q(channel)}, {q(field)}, {q(required)}, {q(max_length)}, {q(max_items)}, {q(built_from)});")
    emit("")

    # ids were set by hand above, so move each table's counter past them
    for table in ("seller_account", "attribute", "item", "raw_import", "source", "fact",
                  "branded_product", "listing", "offer"):
        emit(f"SELECT setval(pg_get_serial_sequence('{table}', 'id'), (SELECT max(id) FROM {table}));")
    emit("COMMIT;")

    open("db/seed.sql", "w").write("\n".join(out) + "\n")
    print(f"db/seed.sql written: {raw_id} raw records, {source_id} sources, {fact_id} facts "
          f"({counts['approved']} approved, {counts['proposed']} proposed, {counts['rejected']} rejected), "
          f"{legacy_listings} legacy listings, {len(DEMO_OFFERS)} managed offers")


if __name__ == "__main__":
    main()
